export type DiagnosticsKey = keyof typeof knowledgeDiagnosticsMessages.en;

export function useDiagnosticsText() {
  const { t, i18n } = useTranslation();
  const language = i18n.resolvedLanguage?.startsWith("zh") ? "zh" : "en";
  return (key: DiagnosticsKey, values: Record<string, string | number> = {}) =>
    t(`knowledge.diagnostics.${key}`, {
      defaultValue: knowledgeDiagnosticsMessages[language][key],
      ...values,
    });
}
